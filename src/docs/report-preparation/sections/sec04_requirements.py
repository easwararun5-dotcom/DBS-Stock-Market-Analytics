"""
sec04_requirements.py - Requirements Analysis and Specification
"""

from docx import Document
from docx.shared import Inches
from report_utils import (
    add_h1, add_h2, add_h3, add_body_p, add_bullet_p, add_callout_box, create_styled_table
)

def build_requirements_analysis(doc: Document):
    """Renders Section 5: Requirements Analysis and System Specification."""
    add_h1(doc, "5. Requirements Analysis and System Specification")
    
    add_body_p(
        doc,
        "A rigorous requirements engineering phase was conducted to define the functional capabilities, performance standards, data integrity constraints, and operational boundaries of the Stock Market Analytics and Portfolio Management System. Requirements are categorized into Functional Requirements (FR) and Non-Functional Requirements (NFR)."
    )
    
    add_h2(doc, "5.1 Functional Requirements (FR)")
    add_bullet_p(
        doc,
        "The system must persist company master entities (ticker, company name, exchange, IPO year) and normalized market sectors in a centralized taxonomy with foreign key cascading rules.",
        bold_prefix="FR1 (Master Taxonomy Management): "
    )
    add_bullet_p(
        doc,
        "The system must ingest and serve chronological OHLCV (Open, High, Low, Close, Volume) daily price data for all tracked enterprise equities across a 5-year historical horizon.",
        bold_prefix="FR2 (Historical Market Series Retrieval): "
    )
    add_bullet_p(
        doc,
        "The system must support native temporal aggregation over arbitrary intervals (e.g., 7-day, 14-day, 30-day, 90-day buckets) using database-tier time-series functions, calculating period open, period high, period low, period close, and total aggregate volume.",
        bold_prefix="FR3 (Dynamic Time-Bucket Aggregations): "
    )
    add_bullet_p(
        doc,
        "Authenticated users must be able to instantiate multiple named paper trading portfolios, each initialized with a virtual cash balance ($100,000 default), and track total valuation, realized gains, and unrealized returns.",
        bold_prefix="FR4 (Multi-Portfolio Lifecycle & Ledger): "
    )
    add_bullet_p(
        doc,
        "The system must execute simulated buy and sell market orders atomically, updating cash balances and average cost bases while strictly preventing overselling or negative cash balances.",
        bold_prefix="FR5 (Concurrency-Safe Paper Trading Execution): "
    )
    add_bullet_p(
        doc,
        "The database must automatically log every transactional mutation (insert, update, delete) into an append-only audit log table, capturing user identity, timestamp, operation type, and modified attributes.",
        bold_prefix="FR6 (Mutation Auditing and Constraint Enforcement): "
    )
    add_bullet_p(
        doc,
        "The system must provide predictive next-day price movement probabilities (UP vs. DOWN) generated by a trained gradient-boosted machine learning model based on extracted technical indicators.",
        bold_prefix="FR7 (Machine Learning Price Forecasting): "
    )
    add_bullet_p(
        doc,
        "The platform must compute comprehensive portfolio risk metrics (Sharpe ratio, maximum drawdown, annual volatility) and decompose asset holdings into normalized sector allocations.",
        bold_prefix="FR8 (Portfolio Risk Analysis & Sector Breakdown): "
    )
    
    add_h2(doc, "5.2 Non-Functional Requirements (NFR)")
    add_bullet_p(
        doc,
        "95% of read-only REST API requests (including OHLCV price queries and dashboard overviews) must resolve within 50 milliseconds under standard concurrency.",
        bold_prefix="NFR1 (Performance and Query Latency): "
    )
    add_bullet_p(
        doc,
        "Transactional paper trading operations must exhibit strict serializability. Under concurrent order executions against the same portfolio, no race conditions, dirty reads, or phantom updates may occur.",
        bold_prefix="NFR2 (Concurrency & Transactional Consistency): "
    )
    add_bullet_p(
        doc,
        "The time-series data store must automatically partition historical prices into time chunks (360-day intervals) to ensure query planner chunk exclusion and prevent B-tree index degradation beyond 1,000,000 rows.",
        bold_prefix="NFR3 (Scalability and Partitioning Efficiency): "
    )
    add_bullet_p(
        doc,
        "User portfolio data must enforce complete tenant isolation via relational foreign key relationships. Passwords and sensitive credentials must never be stored in plaintext or logged.",
        bold_prefix="NFR4 (Data Isolation and Security): "
    )
    add_bullet_p(
        doc,
        "The backend application must feature automated failover; if the secondary time-series engine is temporarily unreachable, read queries must gracefully fall back to the primary PostgreSQL replica without returning 500 Internal Server Errors.",
        bold_prefix="NFR5 (High Availability and Graceful Degradation): "
    )
    
    add_h2(doc, "5.3 Implemented Features vs. Planned / Deferred Features")
    add_body_p(
        doc,
        "To ensure complete academic transparency, the following matrix explicitly delineates features fully implemented and verified in the codebase versus architectural extensions reserved for future work:"
    )
    
    headers = ["Feature / Subsystem", "Implementation Status", "Verification Method / File Path", "Notes & Operational Scope"]
    feat_data = [
        ["Dual Database Tier", "VERIFIED IMPLEMENTED", "docker-compose.yml, backend/app/database.py", "PostgreSQL 18.4 (5435) & TimescaleDB 2.31.0 (5434) actively routed."],
        ["TimescaleDB Hypertables", "VERIFIED IMPLEMENTED", "daily_price_history (28 chunks, 287k rows)", "Native time_bucket() actively queried by FastAPI."],
        ["Pessimistic Concurrency", "VERIFIED IMPLEMENTED", "backend/app/main.py (lines 1241, 1393)", "SELECT ... FOR UPDATE locks on user_portfolio & holdings."],
        ["Audit Trail Triggers", "VERIFIED IMPLEMENTED", "sql/triggers/portfolio_triggers.sql", "trg_portfolio_transaction_audit logs all mutations."],
        ["Oversell Check Trigger", "VERIFIED IMPLEMENTED", "sql/triggers/portfolio_triggers.sql", "trg_portfolio_transaction_consistency validates balances."],
        ["Normalized Schema (16 Tables)", "VERIFIED IMPLEMENTED", "sql/schema/01_core_schema.sql, migration 05", "Pure 3NF/BCNF. Dropped redundant user_id, decomposed JSONB."],
        ["Analytical SQL Views", "VERIFIED IMPLEMENTED", "sql/views/analytical_views.sql", "7 views including v_latest_stock_prices using DISTINCT ON."],
        ["ML Predictive Engine", "VERIFIED IMPLEMENTED", "backend/app/ml/predictive_engine.py", "HistGradientBoostingClassifier with 20 features (54.12% accuracy)."],
        ["React 19 Dashboard", "VERIFIED IMPLEMENTED", "frontend/src/App.tsx, components/", "Vite build passing (140ms). Interactive charts, portfolio cards."],
        ["Database Stored Procedures", "DATABASE IMPLEMENTED", "sql/procedures/trading_procedures.sql", "record_stock_purchase implemented in SQL; FastAPI runs parameterized SQL."],
        ["Live WebSocket Ticker", "DEFERRED / FUTURE", "Simulated historical data used", "Requires external market data feed (e.g. Polygon.io / Alpaca)."],
        ["Options / Derivatives", "DEFERRED / FUTURE", "Equities only currently modeled", "Requires Black-Scholes pricing engine and contract chain schema."]
    ]
    # Total width: 1.5 + 1.4 + 1.8 + 1.8 = 6.50 in
    create_styled_table(
        doc,
        headers,
        feat_data,
        [Inches(1.5), Inches(1.4), Inches(1.8), Inches(1.8)]
    )
    
    # Page break after Section 5
    doc.add_page_break()
